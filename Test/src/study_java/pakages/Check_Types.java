package study_java.pakages;

public class Check_Types {

    public static void main(String[] args) {
        // Wrapper클래스("자료형".valueof = 해당 자료형으로 바꿔줌)
        // 바꿀려는 자료형이 바꿀수 있는 자료형이여야함.
        // ex) true != 15.124;
        Double i = Double.valueOf(1);
        System.out.println(i);
    }

    
}